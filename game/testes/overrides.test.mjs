test('OV7. O JOGO APLICA o que foi salvo: um processo novo (apontado para os overrides) enxerga o monstro alterado, a variação, os ataques novos e ignora o inválido — sem tocar no original', () => {
  limpa();
  E.salvar('troll', { hp: 777, exp: 55, elements: { fire: 60 }, ataques: [{ tipo: 'melee', min: 3, max: 33, intervalo: 1500, chance: 100 }] });
  E.duplicar('troll', 'troll-guerreiro', 'Troll Guerreiro');
  const dados = arquivo();
  dados.monstros.rotworm = { hp: -1 };
  dados.monstros['inexistente-xx'] = { hp: 5 };
  writeFileSync(E.CAMINHOS.arquivo, JSON.stringify(dados));
  const codigo = `const D = await import(${JSON.stringify(new URL('../systems/dados.mjs', import.meta.url).href)});
    const P = await import(${JSON.stringify(new URL('../systems/poderes.mjs', import.meta.url).href)});
    const M = await import(${JSON.stringify(new URL('../systems/hunt/monstros.mjs', import.meta.url).href)});
    const b = D.CATALOGO.bestiary; const m = M.criarMonstro({ key: 'troll', x: 1, y: 1 }, null);
    console.log(JSON.stringify({ hp: b.troll.hp, exp: b.troll.exp, fogo: b.troll.elements.fire, rotworm: b.rotworm.hp, variacao: b['troll-guerreiro']?.name, varHp: b['troll-guerreiro']?.hp, fantasma: !!b['inexistente-xx'], noJogo: m.maxHp, ataque: P.temPoderes({ key: 'troll' }), aplicados: D.resultadoDosOverrides.aplicados, ignorados: D.resultadoDosOverrides.ignorados.map((i) => i.key).sort() }));`;
  const saida = JSON.parse(execFileSync(process.execPath, ['--input-type=module', '-e', codigo], { env: { ...process.env, DRAEVOR_OVERRIDES: pasta }, encoding: 'utf8' }).trim().split('\n').at(-1));
  assert.equal(saida.hp, 777);
  assert.equal(saida.noJogo, 777, 'o bicho que o jogo cria na hunt já nasce com a vida nova');
  assert.equal(saida.exp, 55);
  assert.equal(saida.fogo, 60);
  assert.equal(saida.variacao, 'Troll Guerreiro');
  assert.equal(saida.varHp, 777, 'duplicar um monstro já alterado leva as alterações dele para a variação');
  assert.equal(saida.rotworm, REAL.rotworm.hp, 'override inválido ignorado');
  assert.equal(saida.fantasma, false);
  assert.deepEqual(saida.ignorados, ['inexistente-xx', 'rotworm']);
  assert.deepEqual(saida.aplicados, ['troll']);
  assert.equal(CATALOGO.bestiary.troll.hp, REAL.troll.hp, 'o jogo DESTE processo não mudou (só vale no boot): salvar não é publicar');
  const sem = JSON.parse(execFileSync(process.execPath, ['--input-type=module', '-e', `const D = await import(${JSON.stringify(new URL('../systems/dados.mjs', import.meta.url).href)}); console.log(JSON.stringify({ hp: D.CATALOGO.bestiary.troll.hp }))`], { env: { ...process.env, DRAEVOR_OVERRIDES: join(pasta, 'nao-existe') }, encoding: 'utf8' }).trim().split('\n').at(-1));
  assert.equal(sem.hp, REAL.troll.hp, 'sem arquivo de overrides o jogo é o original');
});

test('OV8. rotas: leitura, pré-visualização (não grava) e ações (gravam); o acesso classifica certo; a tela só usa o servidor', async () => {
  limpa();
  const chama = async (metodo, rota, corpo = {}, query = '') => { const r = []; await Http.atender({ method: metodo }, {}, `/api/mapas/_conteudo/${rota}`, new URL(`http://x/?${query}`), { json: (a, c, b) => r.push([c, b]), corpoJson: async () => corpo }); return r[0]; };
  assert.ok((await chama('GET', 'overrides/monstros', {}, 'q=troll'))[1].total >= 1);
  assert.equal((await chama('GET', 'overrides/monstros/troll'))[1].key, 'troll');
  assert.equal((await chama('GET', 'overrides/monstros/nao-existe'))[0], 404);
  const v = (await chama('POST', 'overrides/validar', { key: 'troll', override: { hp: 100 } }))[1];
  assert.equal(v.ok, true);
  assert.equal(existsSync(E.CAMINHOS.arquivo), false);
  assert.equal((await chama('POST', 'overrides', { acao: 'salvar', key: 'troll', override: { hp: 100 } }))[1].ok, true);
  assert.equal((await chama('POST', 'overrides', { acao: 'duplicar', key: 'troll', novaKey: 'troll-x' }))[1].ok, true);
  assert.equal((await chama('POST', 'overrides', { acao: 'ativo', ativo: false }))[1].ok, true);
  assert.equal((await chama('POST', 'overrides', { acao: 'xyz' }))[0], 400);
  assert.equal((await chama('GET', 'overrides/versoes'))[1].versoes.length >= 1, true);
  assert.equal(A.classeDaRota('POST', '/api/mapas/_conteudo/overrides/validar'), 'leitura');
  assert.equal(A.classeDaRota('POST', '/api/mapas/_conteudo/overrides'), 'grava', 'em produção a gravação é recusada');
  assert.equal(A.classeDaRota('GET', '/api/mapas/_conteudo/overrides/monstros/troll'), 'leitura');
});

test('OV9. a tela: o override em edição fica MÍNIMO (valor igual ao original sai), reconhece alteração real e a ligação com Mobs/Biblioteca/menu existe', async () => {
  const { definirCampo, valorEfetivo, resistenciasEfetivas, alterado, paraEnviar } = await import('../frontend/client/src/editor-mobs.mjs');
  const orig = { name: 'Troll', hp: 50, exp: 20, elements: { fire: 0, energy: 20, earth: -10 }, look: 15 };
  const ov = {};
  definirCampo(orig, ov, 'hp', 80);
  assert.deepEqual(ov, { hp: 80 });
  definirCampo(orig, ov, 'hp', 50);
  assert.deepEqual(ov, {}, 'voltar ao valor original remove o campo do override');
  definirCampo(orig, ov, 'name', '');
  assert.deepEqual(ov, {}, 'vazio não vira override');
  definirCampo(orig, ov, 'elements', { fire: 50, energy: 20, earth: -10 });
  assert.deepEqual(ov.elements, { fire: 50 }, 'só a resistência que difere do original entra');
  assert.deepEqual(resistenciasEfetivas(orig, ov), { fire: 50, energy: 20, earth: -10 });
  definirCampo(orig, ov, 'elements', { fire: 0, energy: 20, earth: -10 });
  assert.equal(ov.elements, undefined);
  ov.exp = 30;
  assert.equal(valorEfetivo(orig, ov, 'exp'), 30);
  assert.equal(valorEfetivo(orig, ov, 'hp'), 50);
  assert.equal(alterado({ hp: 80 }, { hp: 80 }), false);
  assert.equal(alterado({ hp: 90 }, { hp: 80 }), true);
  assert.equal(alterado({ hp: 80, ativo: false }, { hp: 80 }), false, 'ligar/desligar não conta como edição');
  assert.equal(alterado({ base: 'troll', name: 'X' }, { base: 'troll', name: 'X' }), false, 'variação recém-aberta não está suja');
  assert.equal(paraEnviar({}), null);
  assert.equal(paraEnviar({ ativo: false }), null);
  assert.deepEqual(paraEnviar({ hp: 1 }), { hp: 1 });
  const conteudo = readFileSync(new URL('../frontend/client/src/editor-conteudo.mjs', import.meta.url), 'utf8');
  assert.match(conteudo, /criarEditorDeMobs/);
  assert.match(conteudo, /Editar mobs \(overrides\)/);
  assert.match(conteudo, /modo: 'parcial', dica: 'consulta e edição por override/);
  assert.match(readFileSync(new URL('../frontend/client/src/editor-biblioteca.mjs', import.meta.url), 'utf8'), /acaoDaFicha/);
  const tela = readFileSync(new URL('../frontend/client/src/editor-mobs.mjs', import.meta.url), 'utf8');
  for (const r of ["'overrides/validar'", "'overrides'", 'overrides/monstros']) assert.ok(tela.includes(r), r);
  assert.match(tela, /confirmar\(/);
  assert.match(tela, /original: \$\{texto\}/, 'o original aparece ao lado de cada campo');
});
