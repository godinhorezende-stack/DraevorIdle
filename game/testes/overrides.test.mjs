  assert.deepEqual(arquivo().monstros['troll-guerreiro'].ativo, false);
  assert.equal(E.definirAtivo(true, 'troll-guerreiro').ok, true);
  assert.equal(E.definirAtivo(false).ok, true);
  assert.equal(arquivo().ativo, false);
  assert.equal(Object.keys(arquivo().monstros).length, 1, 'desligar não apaga');
